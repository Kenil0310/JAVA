

public class Operator {

    public static void main(String[] args)
    {
        System.out.print("value of 10 + 20 * 30 : \n" + 10 + 20 * 30);
        System.out.print("value of  100 / 10 * 100 : \n" +  100 / 10 * 100);
        System.out.print("value of 5 * 4 / 4 % 3 : \n" + 5 * 4 / 4 % 3);
        System.out.println("value of 100 + 200 / 10 – 3 * 10 : \n" + (100 + 200 / 10 - 3 * 10));
    }
}